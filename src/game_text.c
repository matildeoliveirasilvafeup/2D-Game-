void draw_digit(int x, int y, int digit, uint32_t color) {
    static const uint8_t font[10][5] = {
        {0x7,0x5,0x5,0x5,0x7}, {0x2,0x6,0x2,0x2,0x7},
        {0x7,0x1,0x7,0x4,0x7}, {0x7,0x1,0x3,0x1,0x7},
        {0x5,0x5,0x7,0x1,0x1}, {0x7,0x4,0x7,0x1,0x7},
        {0x7,0x4,0x7,0x5,0x7}, {0x7,0x1,0x1,0x1,0x1},
        {0x7,0x5,0x7,0x5,0x7}, {0x7,0x5,0x7,0x1,0x7},
    };
    int px = 3;
    if (digit < 0 || digit > 9) return;
    for (int r = 0; r < 5; r++)
        for (int c = 0; c < 3; c++)
            if (font[digit][r] & (0x4 >> c))
                draw_rectangle(x + c * px, y + r * px, px, px, color);
}

/* Draw a three-digit number (0-999) at (x, y) */
void draw_number(int x, int y, int n, uint32_t color) {
    if (n < 0) n = 0;
    if (n > 999) n = 999;
    draw_digit(x,    y, n / 100,      color);
    draw_digit(x+12, y, (n / 10) % 10, color);
    draw_digit(x+24, y, n % 10,        color);
}

/* Return the bitmap row for a given character from the built-in 5├ù7 font */
uint8_t glyph_row(char ch, int row) {
    static const uint8_t digits[10][7] = {
        {0x0E,0x11,0x13,0x15,0x19,0x11,0x0E}, {0x04,0x0C,0x04,0x04,0x04,0x04,0x0E},
        {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F}, {0x1E,0x01,0x01,0x0E,0x01,0x01,0x1E},
        {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02}, {0x1F,0x10,0x10,0x1E,0x01,0x01,0x1E},
        {0x0E,0x10,0x10,0x1E,0x11,0x11,0x0E}, {0x1F,0x01,0x02,0x04,0x08,0x08,0x08},
        {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E}, {0x0E,0x11,0x11,0x0F,0x01,0x01,0x0E},
    };
    if (ch >= '0' && ch <= '9') return digits[ch - '0'][row];

    /* Uppercase alphabet and a small set of punctuation characters */
    static const uint8_t alpha[26][7] = {
        {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11}, /* A */
        {0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E}, /* B */
        {0x0F,0x10,0x10,0x10,0x10,0x10,0x0F}, /* C */
        {0x1E,0x11,0x11,0x11,0x11,0x11,0x1E}, /* D */
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F}, /* E */
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x10}, /* F */
        {0x0F,0x10,0x10,0x13,0x11,0x11,0x0F}, /* G */
        {0x11,0x11,0x11,0x1F,0x11,0x11,0x11}, /* H */
        {0x0E,0x04,0x04,0x04,0x04,0x04,0x0E}, /* I */
        {0x0E,0x02,0x02,0x02,0x02,0x12,0x0C}, /* J */
        {0x11,0x12,0x14,0x18,0x14,0x12,0x11}, /* K */
        {0x10,0x10,0x10,0x10,0x10,0x10,0x1F}, /* L */
        {0x11,0x1B,0x15,0x15,0x11,0x11,0x11}, /* M */
        {0x11,0x19,0x15,0x13,0x11,0x11,0x11}, /* N */
        {0x0E,0x11,0x11,0x11,0x11,0x11,0x0E}, /* O */
        {0x1E,0x11,0x11,0x1E,0x10,0x10,0x10}, /* P */
        {0x0E,0x11,0x11,0x11,0x15,0x12,0x0D}, /* Q */
        {0x1E,0x11,0x11,0x1E,0x14,0x12,0x11}, /* R */
        {0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E}, /* S */
        {0x1F,0x04,0x04,0x04,0x04,0x04,0x04}, /* T */
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0E}, /* U */
        {0x11,0x11,0x11,0x11,0x0A,0x0A,0x04}, /* V */
        {0x11,0x11,0x11,0x15,0x15,0x15,0x0A}, /* W */
        {0x11,0x11,0x0A,0x04,0x0A,0x11,0x11}, /* X */
        {0x11,0x11,0x0A,0x04,0x04,0x04,0x04}, /* Y */
        {0x1F,0x01,0x02,0x04,0x08,0x10,0x1F}, /* Z */
    };
    if (ch >= 'A' && ch <= 'Z') return alpha[ch - 'A'][row];

    switch (ch) {
        case ':': { static const uint8_t g[7]={0x00,0x04,0x04,0x00,0x04,0x04,0x00}; return g[row]; }
        case '/': { static const uint8_t g[7]={0x01,0x01,0x02,0x04,0x08,0x10,0x10}; return g[row]; }
        case '-': { static const uint8_t g[7]={0x00,0x00,0x00,0x1F,0x00,0x00,0x00}; return g[row]; }
        case '(': { static const uint8_t g[7]={0x06,0x08,0x10,0x10,0x10,0x08,0x06}; return g[row]; }
        case ')': { static const uint8_t g[7]={0x0C,0x02,0x01,0x01,0x01,0x02,0x0C}; return g[row]; }
    }
    return 0;
}

/* Render a string at (x,y); supports newlines and spaces; scale applies to each pixel */
void draw_text(int x, int y, const char *text, uint32_t color, int scale) {
    int start_x = x;
    for (int i = 0; text[i]; i++) {
        if (text[i] == '\n') { y += 9 * scale; x = start_x; continue; }
        if (text[i] == ' ')  { x += 6 * scale; continue; }
        for (int row = 0; row < 7; row++) {
            uint8_t bits = glyph_row(text[i], row);
            for (int col = 0; col < 5; col++)
                if (bits & (0x10 >> col))
                    draw_rectangle(x + col * scale, y + row * scale, scale, scale, color);
        }
        x += 6 * scale;
    }
}

/* Render an integer value as decimal text */
void draw_int_text(int x, int y, int value, uint32_t color, int scale) {
    char buf[8]; int pos = 0;
    if (value < 0) value = 0;
    if (value == 0) { buf[pos++] = '0'; }
    else {
        char rev[8]; int n = 0;
        while (value > 0 && n < 7) { rev[n++] = (char)('0' + value % 10); value /= 10; }
        while (n > 0) buf[pos++] = rev[--n];
    }
    buf[pos] = '\0';
    draw_text(x, y, buf, color, scale);
}

/* Width of a string in pixels at the given scale */
int text_width(const char *s, int scale) {
    int n = 0;
    for (; *s; s++) n++;
    return n * 6 * scale;
}

/* Render text centred horizontally within a box of width w starting at x */
void draw_text_centred(int x, int w, int y, const char *t, uint32_t c, int scale) {
    draw_text(x + (w - text_width(t, scale)) / 2, y, t, c, scale);
}

